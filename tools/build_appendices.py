def slug(text):
    """GitHub-style heading id."""
    s = re.sub(r"[^\w\- ]", "", text.lower()).strip()
    return s.replace(" ", "-")


def parts():
    """{folder number: part title} from book/OUTLINE.md."""
    out = {}
    for line in (BOOK / "OUTLINE.md").read_text().splitlines():
        m = re.match(r"## Part (\d+): (.+)", line)
        if m:
            out[int(m.group(1))] = m.group(2).strip()
    return out


def pages():
    """Every written page with recommendations, in book order."""
    result = []
    for path in sorted(BOOK.glob("0[1-8]-*/[0-9]*.md")):
        text = path.read_text()
        recs = []
        matches = list(REC_RE.finditer(text))
        for i, m in enumerate(matches):
            end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
            body = text[m.start():end].split("\n## Related")[0]
            src = re.search(r"^\*\*Sources:\*\*(.+?)(?=^\*Last reviewed|\Z)", body, re.M | re.S)
            recs.append({
                "id": m.group(1),
                "title": m.group(2).strip(),
                "anchor": slug(m.group(0)[3:]),
                "body": body,
                "sources": src.group(1) if src else "",
            })
        intro = text[: matches[0].start()] if matches else text
        result.append({
            "rel": path.relative_to(BOOK).as_posix(),
            "part": int(path.parent.name[:2]),
            "title": text.splitlines()[0].lstrip("# ").strip(),
            "recs": recs,
            "intro": intro,
        })
    return result


def link(page, rec=None):
    target = f"../{page['rel']}"
    return f"{target}#{rec['anchor']}" if rec else target


def rec_link(page, rec):
    return f"[{rec['id']}]({link(page, rec)})"


def build_checklist(pgs, titles):
    n = sum(len(p["recs"]) for p in pgs)
    lines = [
        GENERATED, "",
        "# Appendix A: Pre-release checklist", "",
        f"Every recommendation in the book, {n} in all, as one line you can tick.",
        "Work through it before you release a design.",
        "Each line links to the full recommendation, which gives the reasons and the numbers.",
        "These are recommendations, not rules: where you choose not to follow one, it helps to tell your manufacturer why.",
        "",
    ]
    part = None
    for p in pgs:
        if not p["recs"]:
            continue
        if p["part"] != part:
            part = p["part"]
            lines += [f"## Part {part}: {titles[part]}", ""]
        lines += [f"### [{p['title']}]({link(p)})", ""]
        lines += [f"- [ ] **{r['id']}:** [{r['title']}]({link(p, r)})" for r in p["recs"]]
        lines.append("")
    return "\n".join(lines) + FOOTER


def build_stage_index(pgs):
    data = yaml.safe_load(STAGES_FILE.read_text()) or {}
    all_recs = {r["id"]: (p, r) for p in pgs for r in p["recs"]}
    problems = [f"{i}: not tagged" for i in all_recs if i not in data]
    problems += [f"{i}: tagged but not in the book" for i in data if i not in all_recs]
    for i, stages in data.items():
        for s in stages or []:
            if s not in STAGES:
                problems.append(f"{i}: unknown stage {s!r}")
    if problems:
        sys.exit("design-stages.yaml:\n  " + "\n  ".join(problems))
    lines = [
        GENERATED, "",
        "# Appendix B: Index by design stage", "",
        "The book is ordered by how a board is built.",
        "This index orders the same recommendations by when you meet them while designing.",
        "A recommendation that matters at two stages is listed under both.",
        "",
    ]
    for key, name in STAGES.items():
        ids = [i for i in all_recs if key in (data.get(i) or [])]
        lines += [f"## {name}", "", STAGE_INTRO[key], ""]
        lines += [f"- **{i}:** [{all_recs[i][1]['title']}]({link(*all_recs[i])})" for i in ids]
        lines.append("")
    return "\n".join(lines) + FOOTER


def build_standards(pgs):
    cites = defaultdict(list)    # base -> [(page, rec)]
    editions = defaultdict(set)  # base -> {cited codes}
    pages_only = defaultdict(list)
    unknown = set()

    def scan(text):
        found = {}
        for m in STD_RE.finditer(text):
            code = m.group(1)
            base = re.sub(r"(\d)[A-Z]$", r"\1", code)
            if base not in STANDARDS:
                unknown.add(code)
                continue
            found[base] = code
        return found

    for p in pgs:
        for base, code in scan(p["intro"]).items():
            editions[base].add(code)
            pages_only[base].append(p)
        for r in p["recs"]:
            for base, code in scan(r["body"]).items():
                editions[base].add(code)
                cites[base].append((p, r))
    if unknown:
        sys.exit("Standards with no title in STANDARDS: " + ", ".join(sorted(unknown)))
    keys = sorted(set(cites) | set(pages_only), key=lambda k: [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", k)])
    lines = [
        GENERATED, "",
        "# Appendix D: Standards referenced", "",
        f"The book refers to {len(keys)} published standards.",
        "Each is listed with its full title and the recommendations that mention it.",
        "Where the book names a particular revision, it is given after the title.",
        "Standards are revised every few years, so check that you have the current revision.",
        "",
        "| Standard | Title | Mentioned in |",
        "|---|---|---|",
    ]
    for k in keys:
        revs = sorted(c for c in editions[k] if c != k)
        title = STANDARDS[k] + (f" (cited as {', '.join(revs)})" if revs else "")
        refs = [rec_link(p, r) for p, r in cites[k]]
        refs += [f"[{p['title']}]({link(p)})" for p in pages_only[k] if all(p is not q for q, _ in cites[k])]
        lines.append(f"| {k} | {title} | {', '.join(refs)} |")
    lines.append("")
    return "\n".join(lines) + FOOTER


def build_sources(pgs):
    episodes = {}               # id -> {title, url, date, recs}
    other = OrderedDict()       # url -> {text, recs}
    for p in pgs:
        for r in p["recs"]:
            src = r["sources"].replace("\n", " ")
            for m in EPISODE_RE.finditer(src):
                title, url, eid, date = m.groups()
                e = episodes.setdefault(eid, {"title": title, "url": url, "date": date, "recs": []})
                if r["id"] not in [x[1]["id"] for x in e["recs"]]:
                    e["recs"].append((p, r))
            for m in LINK_RE.finditer(src):
                text, url = m.groups()
                if "buzzsprout.com" in url:
                    continue
                o = other.setdefault(url, {"text": text, "recs": []})
                if r["id"] not in [x[1]["id"] for x in o["recs"]]:
                    o["recs"].append((p, r))

    def when(date):
        m = re.match(r"([A-Z][a-z]{2})\w* (\d{4})", date)
        months = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()
        return (int(m.group(2)), months.index(m.group(1)) + 1) if m else (9999, 0)

    eps = sorted(episodes.values(), key=lambda e: when(e["date"]))
    lines = [
        GENERATED, "",
        "# Appendix E: Sources", "",
        "Much of this book's advice was first discussed on the Pick, Place, Podcast, which began in 2020 and is still running.",
        f"The book cites {len(eps)} of its episodes.",
        "Each recommendation's own Sources line gives timestamps that link to the exact moment in the episode.",
        "Advice from the author's own experience is cited as \"Chris Denney (author)\".",
        "",
        "## Pick, Place, Podcast episodes", "",
        "In order of publication.", "",
        "| Episode | Date | Cited in |",
        "|---|---|---|",
    ]
    for e in eps:
        t = e["title"].replace("|", "\\|")
        lines.append(f"| [{t}]({e['url']}) | {e['date']} | {', '.join(rec_link(p, r) for p, r in e['recs'])} |")
    lines += [
        "", "## Other published documents", "",
        "Documents the book links to.",
        "Recommendations also draw on published guidance from fabricators, assemblers and component makers, described in their Sources lines without a link.",
        "", "| Document | Cited in |", "|---|---|",
    ]
    for url, o in other.items():
        lines.append(f"| [{o['text']}]({url}) | {', '.join(rec_link(p, r) for p, r in o['recs'])} |")
    lines.append("")
    return "\n".join(lines) + FOOTER


def main():
    check = "--check" in sys.argv
    pgs = pages()
    titles = parts()
    outputs = {
        "01-checklist.md": build_checklist(pgs, titles),
        "02-design-stage-index.md": build_stage_index(pgs),
        "04-standards.md": build_standards(pgs),
        "05-sources.md": build_sources(pgs),
    }
    OUT.mkdir(exist_ok=True)
    stale = []
    for name, text in outputs.items():
        path = OUT / name
        if path.exists() and path.read_text() == text:
            continue
        stale.append(name)
        if not check:
            path.write_text(text)
    if check and stale:
        sys.exit("Out of date (run python3 tools/build_appendices.py): " + ", ".join(stale))
    n = sum(len(p["recs"]) for p in pgs)
    print(f"{n} recommendations; {'checked' if check else 'wrote'} {len(outputs)} files" + (f" ({', '.join(stale)} changed)" if stale else ""))


if __name__ == "__main__":
    main()
