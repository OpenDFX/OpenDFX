"""Build the generated appendices from the book's pages, so they never drift from the text.

Run: python3 tools/build_appendices.py          (writes the files)
     python3 tools/build_appendices.py --check  (exits 1 if any file is out of date)

Writes into book/09-appendices/:
  01-checklist.md           A. Pre-release checklist: every recommendation as one checkable line
  02-design-stage-index.md  B. Index by design stage, from book/09-appendices/design-stages.yaml
  04-standards.md           D. Standards referenced, and the recommendations that cite each one
  05-sources.md             E. Sources: every podcast episode and published document cited

The glossary (03-glossary.md) is written by hand.
"""
import re
import sys
from collections import OrderedDict, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
BOOK = ROOT / "book"
OUT = BOOK / "09-appendices"
STAGES_FILE = OUT / "design-stages.yaml"

GENERATED = "<!-- Generated by tools/build_appendices.py from the book's pages. Don't edit by hand; edit the pages and run the script. -->"
FOOTER = "\n---\n*From OpenDFX for Printed Circuit Boards by Chris Denney · CC BY-SA 4.0*\n"

REC_RE = re.compile(r"^## (PCB-(?:DFA|DFM|DFT)-\d{3}): (.+)$", re.M)
EPISODE_RE = re.compile(
    r"\[[“\"](.+?)[”\"]\]\((https://www\.buzzsprout\.com/1066066/episodes/(\d+)[^)\s]*)\)\s*\(([^)]+)\)"
)
LINK_RE = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")
STD_RE = re.compile(
    r"\b(?:ANSI/)?(?:JEDEC )?"
    r"(IPC-[A-Z]+-\d+[A-Z]?|IPC-\d{4}[A-Z]?|J-STD-\d{3}[A-Z]?|EIA-\d{3}[A-Z]?|"
    r"ESD S\d+(?:\.\d+)?|ESD STM\d+(?:\.\d+)?|IEC \d{5}(?:-\d+)*)"
)

