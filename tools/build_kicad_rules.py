"""Build the OpenDFX KiCad design-rules file from tools/kicad_rules.yaml (M12).

Run: python3 tools/build_kicad_rules.py          (writes the file)
     python3 tools/build_kicad_rules.py --check  (exits 1 if it is out of date)

Writes kicad/opendfx.kicad_dru, and copies it into the starter project as kicad/opendfx-starter/opendfx-starter.kicad_dru,
because KiCad only reads a rules file named after its project, and into public/ for the website's download link.
Also writes the website's page about it, site/src/content/docs/kicad.mdx, with its table of checks.

Before writing, it checks that every value in kicad_rules.yaml appears in the text of the recommendation it names,
so the rules file can't drift from the book.
"""
