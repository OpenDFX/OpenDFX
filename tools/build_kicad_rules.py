# Constraints that compare two items, so the rule area applies if either item is inside it.
PAIRS = ("physical_clearance", "physical_hole_clearance", "silk_clearance")


def load():
    return yaml.safe_load(SOURCE.read_text())["checks"]


def values_by_id():
    """{id: [{check, minimum, recommended, unit}]} for the data file (Q137): the book's numbers for each check."""
    out = {}
    for c in load():
        if "recommended" not in c:
            continue
        for rid in c["ids"]:
            out.setdefault(rid, []).append({
                "check": c["what"],
                "minimum": float(c["minimum"]),
                "recommended": float(c["recommended"]),
                "unit": "mm",
            })
    return out


def book_text():
    """{id: all the text of one recommendation}, read straight from the book's pages."""
    sys.path.insert(0, str(ROOT / "tools"))
    import build_data as bd  # imported here, because build_data imports this file
    recs = bd.build_records(bd.ba.pages(), bd.ba.parts())
    keys = ("title", "recommendation", "why", "typical_values", "what_goes_wrong")
    return {r["id"]: " ".join(r.get(k) or "" for k in keys) for r in recs}


def number_in(value, text):
    """True if the number appears in the text as a whole number token (0.15 doesn't match 0.155 or 10.15)."""
    v = value.rstrip("0").rstrip(".") if "." in value else value
    pattern = r"(?<![\d.])" + re.escape(v) + r"(?:\.0+)?(?![\d])"
    return re.search(pattern, text) is not None


def verify(checks):
    texts = book_text()
    problems = []
    for c in checks:
        for rid in c["ids"]:
            if rid not in texts:
                problems.append(f"{c['key']}: {rid} is not in the book")
        for tier in ("recommended", "minimum"):
            if tier in c and not any(number_in(c[tier], texts.get(rid, "")) for rid in c["ids"]):
                problems.append(f"{c['key']}: the {tier} value {c[tier]} mm is not in the text of {', '.join(c['ids'])}")
    if problems:
        sys.exit("kicad_rules.yaml doesn't match the book:\n  " + "\n  ".join(problems))


def kind(constraint):
    return constraint.split()[0]


def area_test(constraint):
    if kind(constraint) in PAIRS:
        return f"(A.intersectsArea('{AREA}') || B.intersectsArea('{AREA}'))"
    return f"A.intersectsArea('{AREA}')"


def rule(name, constraint, condition, layer=None, severity=None):
    lines = [f'(rule "{name}"']
    if layer:
        lines.append(f'  (layer "{layer}")')
    lines.append(f"  (constraint {constraint})")
    lines.append(f'  (condition "{condition}")')
    if severity and severity != "error":
        lines.append(f"  (severity {severity})")
    return "\n".join(lines) + ")\n"


def fill(text, value, extra_vars):
    return text.replace("{value}", value).format(**extra_vars) if extra_vars else text.replace("{value}", value)


def rules_for(c):
    rid = c["ids"][0]
    parts = [(c["constraint"], c["condition"])] + [(e["constraint"], e["condition"]) for e in c.get("extra", [])]
    layer, severity = c.get("layer"), c.get("severity")
    out = [f"\n# {c['what']}. {', '.join(c['ids'])}\n"]
    if "recommended" not in c:  # a check with no numbers
        name = f"{rid}: {c['message']} ({SITE}/{rid})"
        for constraint, condition in parts:
            out.append(rule(name, constraint, condition, layer, severity))
        return "".join(out)
    rec, low = c["recommended"], c["minimum"]
    if c.get("rules_file_checks") == "minimum":
        rec = low
    vars_ = c.get("vars", {})
    if rec == low:
        name = f"{rid}: {fill(c['message'], rec, {})} ({SITE}/{rid})"
        for constraint, condition in parts:
            out.append(rule(name, fill(constraint, rec, vars_.get("minimum")), condition, layer, severity))
        return "".join(out)
    for tier, value, inside in (("recommended", rec, False), ("minimum", low, True)):
        where = ", inside an OpenDFX minimum area" if inside else ""
        name = f"{rid}: {fill(c['message'], value, {})}{where} ({SITE}/{rid})"
        for constraint, condition in parts:
            test = area_test(constraint)
            cond = f"{condition} && {test}" if inside else f"{condition} && !{test}"
            out.append(rule(name, fill(constraint, value, vars_.get(tier)), cond, layer, severity))
    return "".join(out)


def build(checks):
    return HEADER + "".join(rules_for(c) for c in checks if "board_setting" not in c) + FOOTER


